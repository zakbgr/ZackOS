#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
set -u
HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=tests/shell/harness.sh
source "${HERE}/harness.sh"
# shellcheck source=lib/repo.sh
source "${HERE}/../../lib/repo.sh"

make_tmp
use_fakebin
export NO_COLOR=1
SPEC="lionheartp/Hyprland"
ID="copr:copr.fedorainfracloud.org:lionheartp:Hyprland"

# ---- ids and names
assert_eq "${ID}" "$(repo_copr_id "${SPEC}")" "repo id"
assert_eq "50-zackos-isolation-lionheartp-Hyprland.repo" "$(repo_override_filename "${SPEC}")" "override file name"
assert_rc 2 "bad spec" repo_copr_id 'a b'
assert_rc 2 "bad spec 2" repo_copr_id 'no-slash'

# ---- allowlist comes from the manifest
assert_eq "hyprland
uwsm
xdg-desktop-portal-hyprland" "$(repo_allowlist "${SPEC}")" "allowlist from manifest"
assert_eq "" "$(repo_allowlist someone/else)" "no packages for another COPR"

# ---- generator
mapfile -t AL < <(repo_allowlist "${SPEC}")
out="$(repo_generate_override "${ID}" "${AL[@]}")"
assert_contains "${out}" "[${ID}]" "section header is the colon-containing repo id"
assert_contains "${out}" "includepkgs=hyprland,uwsm,xdg-desktop-portal-hyprland" "includepkgs is the sorted allowlist"
assert_contains "${out}" "excludepkgs=*-git,kitty,zsh,neovim" "excludepkgs second layer lists -git and protected names"
assert_eq "no" "$(grep '^includepkgs=' <<<"${out}" | grep -q 'kitty\|waybar\|git' && echo yes || echo no)" "includepkgs has no protected or git entries"
assert_eq "${out}" "$(repo_generate_override "${ID}" "${AL[@]}")" "deterministic"
assert_eq "${out}" "$(repo_generate_override "${ID}" uwsm hyprland xdg-desktop-portal-hyprland hyprland)" "order and duplicate input do not change output"
assert_contains "${out}" "GENERATED BY ZACKOS" "header"

# ---- generator refuses dangerous input
for bad in kitty waybar hyprland-git 'hypr*' 'a,b' 'a b' '' ; do
    assert_rc 1 "generator refuses '${bad}'" repo_generate_override "${ID}" hyprland "${bad}"
done
assert_rc 1 "empty allowlist refused" repo_generate_override "${ID}"
assert_rc 2 "bad repo id refused" repo_generate_override 'bad id' hyprland
assert_rc 2 "bad repo id with newline refused" repo_generate_override $'x\ny' hyprland

# ---- audit
audit() { printf '%b' "$1" | repo_audit "${SPEC}"; }
assert_rc 0 "clean system passes" bash -c "source '${HERE}/../../lib/repo.sh'; printf 'kitty\tfedora\nzsh\tupdates\n' | repo_audit ${SPEC}"
assert_rc 0 "allowlisted package from our COPR passes" bash -c "source '${HERE}/../../lib/repo.sh'; printf 'hyprland\t${ID}\n' | repo_audit ${SPEC}"
res="$(audit "kitty\t${ID}\n" 2>&1 || true)"
assert_contains "${res}" "VIOLATION	kitty" "protected package from the COPR is flagged"
res="$(audit "foo\t${ID}\n" 2>&1 || true)"
assert_contains "${res}" "not in the allowlist" "unlisted COPR package flagged"
res="$(audit "hyprland\tcopr:copr.fedorainfracloud.org:other:thing\n" 2>&1 || true)"
assert_contains "${res}" "COPR that ZackOS does not use" "package from a different COPR flagged"
res="$(audit "zsh\trpmfusion-free\n" 2>&1 || true)"
assert_contains "${res}" "manifest requires fedora" "fedora-only package from a third-party repo flagged"
assert_rc 1 "audit returns 1 on violation" bash -c "source '${HERE}/../../lib/repo.sh'; printf 'kitty\t${ID}\n' | repo_audit ${SPEC}"

# ---- closure gaps
gaps() { printf '%b' "$1" | repo_closure_gaps "${SPEC}" hyprland aquamarine; }
assert_rc 0 "closed allowlist" bash -c "source '${HERE}/../../lib/repo.sh'; printf 'hyprland\taquamarine\t${ID}\nhyprland\tglibc\tfedora\n' | repo_closure_gaps ${SPEC} hyprland aquamarine"
res="$(gaps "hyprland\thyprutils\t${ID}\n" 2>&1 || true)"
assert_contains "${res}" "GAP	hyprland	requires hyprutils" "missing COPR dependency detected"
res="$(gaps "hyprland\tglibc\tfedora\n" 2>&1 || true)"
assert_eq "" "${res}" "Fedora-provided dependencies are not gaps"
res="$(gaps "otherpkg\thyprutils\t${ID}\n" 2>&1 || true)"
assert_eq "" "${res}" "only allowlisted packages are checked"

# ---- command builders print, never execute
OVERRIDE_SRC="/tmp/example.repo"
steps="$(repo_enable_steps "${SPEC}")"
first="$(head -n1 <<<"${steps}")"
second="$(sed -n 2p <<<"${steps}")"
assert_contains "${first}" "Write the isolation override" "override is written first"
assert_contains "${second}" "dnf5 copr enable ${SPEC} fedora-44-x86_64" "enable is second, chroot explicit"
assert_contains "${first}" "/etc/dnf/repos.override.d/50-zackos-isolation-lionheartp-Hyprland.repo" "override path"
assert_contains "${steps}" "dnf5 copr disable ${SPEC}" "undo for enable"
assert_contains "$(repo_disable_steps "${SPEC}")" "sudo dnf5 copr disable ${SPEC}" "disable step"
assert_eq "" "$(cat "${FAKE_LOG}")" "building steps ran nothing"

# ---- execution is LOCKED, even with --apply
rc=0
ZACKOS_APPLY=1 repo_enable_execute >/dev/null 2>&1 || rc=$?
assert_eq "5" "${rc}" "enable is locked (exit 5)"
rc=0
ZACKOS_APPLY=1 repo_disable_execute >/dev/null 2>&1 || rc=$?
assert_eq "5" "${rc}" "disable is locked (exit 5)"
assert_eq "" "$(cat "${FAKE_LOG}")" "locked operations called neither sudo nor dnf5"
assert_eq "1" "${ZACKOS_COPR_OPS_LOCKED}" "lock constant is set"
assert_rc 1 "lock constant is readonly" bash -c "source '${HERE}/../../lib/repo.sh'; ZACKOS_COPR_OPS_LOCKED=0"

t_finish
