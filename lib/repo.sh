#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Repository isolation (docs/PACKAGE-POLICY.md, ADR 0005).
#
#   - generates the DNF5 override that restricts a COPR repository to an allowlist
#   - audits installed packages against the manifest
#   - checks that COPR dependencies of allowlisted packages are allowlisted too
#   - builds (prints) the steps for enabling/disabling a COPR
#
# Nothing here writes to /etc or runs a privileged command. The execution functions for
# enabling/disabling a COPR are LOCKED and return ZACKOS_EXIT_LOCKED.

[[ -n "${_ZACKOS_REPO_LOADED:-}" ]] && return 0
_ZACKOS_REPO_LOADED=1

_ZACKOS_LIB_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/log.sh
source "${_ZACKOS_LIB_DIR}/log.sh"
# shellcheck source=lib/dnf.sh
source "${_ZACKOS_LIB_DIR}/dnf.sh"
# shellcheck source=lib/pkg.sh
source "${_ZACKOS_LIB_DIR}/pkg.sh"

# Hard lock: COPR operations stay unavailable until the owner approves unlocking them in a
# later phase. Changing this constant is a reviewed, explicit code change.
readonly ZACKOS_COPR_OPS_LOCKED=1

readonly REPO_OVERRIDE_DIR="/etc/dnf/repos.override.d"
readonly REPO_DEFAULT_CHROOT="fedora-44-x86_64"

# repo_valid_spec <owner/project>
repo_valid_spec() {
    [[ "${1:-}" =~ ^[A-Za-z0-9._-]+/[A-Za-z0-9._-]+$ ]]
}

# repo_copr_id <owner/project>: the DNF repo ID that dnf5 copr gives the repository.
repo_copr_id() {
    repo_valid_spec "${1:-}" || return 2
    printf 'copr:copr.fedorainfracloud.org:%s:%s' "${1%%/*}" "${1#*/}"
}

# repo_override_filename <owner/project>: the single file ZackOS owns in the override dir.
repo_override_filename() {
    repo_valid_spec "${1:-}" || return 2
    printf '50-zackos-isolation-%s-%s.repo' "${1%%/*}" "${1#*/}"
}

# repo_allowlist <owner/project>: manifest packages whose source is this COPR, sorted.
repo_allowlist() {
    local spec="${1:?owner/project required}" name source rest
    while IFS=$'\t' read -r name source rest; do
        [[ "${source}" == "copr:${spec}" ]] && printf '%s\n' "${name}"
    done < <(pkg_rows) | sort -u
}

# repo_validate_allowlist <name>...: refuse anything that could weaken isolation.
repo_validate_allowlist() {
    local bad=0 name seen=" "
    if (($# == 0)); then
        log_error "allowlist is empty: refusing to generate an override"
        return 1
    fi
    for name in "$@"; do
        if ! dnf_valid_name "${name}"; then
            log_error "invalid allowlist entry '${name}' (no globs, commas or spaces)"
            bad=1
            continue
        fi
        if [[ "${name}" == *-git ]]; then
            log_error "allowlist entry '${name}' is a -git package"
            bad=1
        fi
        if pkg_is_protected "${name}"; then
            log_error "allowlist entry '${name}' is a protected package that must come from Fedora"
            bad=1
        fi
        if [[ "${seen}" == *" ${name} "* ]]; then
            log_error "duplicate allowlist entry '${name}'"
            bad=1
        fi
        seen+="${name} "
    done
    return "${bad}"
}

# repo_generate_override <repo-id> <name>...: print the override file (deterministic).
# includepkgs is the allowlist; excludepkgs repeats the protected names and *-git as a second
# layer, because DNF5 applies both and includepkgs never overrides excludepkgs.
repo_generate_override() {
    local id="${1:?repo id required}" names=() joined excluded
    shift
    [[ "${id}" =~ ^[A-Za-z0-9._:@-]+$ ]] || {
        log_error "invalid repository id '${id}'"
        return 2
    }
    mapfile -t names < <(printf '%s\n' "$@" | sort -u)
    repo_validate_allowlist "${names[@]}" || return 1
    joined="$(
        IFS=,
        printf '%s' "${names[*]}"
    )"
    excluded="$(
        IFS=,
        printf '%s' "*-git,${PKG_PROTECTED[*]}"
    )"
    cat <<EOF
# SPDX-License-Identifier: GPL-3.0-or-later
# GENERATED BY ZACKOS. DO NOT EDIT. See docs/PACKAGE-POLICY.md.
# Restricts this repository to an allowlist so it cannot replace Fedora packages.
[${id}]
includepkgs=${joined}
excludepkgs=${excluded}
EOF
}

# repo_audit <owner/project>: reads "name<TAB>origin" lines on stdin (installed packages).
# Prints one VIOLATION line per problem; returns 1 if any were found.
repo_audit() {
    local spec="${1:?owner/project required}" id allow name origin class source bad=0
    id="$(repo_copr_id "${spec}")" || return 2
    allow=" $(repo_allowlist "${spec}" | tr '\n' ' ')"
    while IFS=$'\t' read -r name origin; do
        [[ -n "${name}" ]] || continue
        class="$(dnf_origin_class "${origin}")"
        source="$(pkg_source "${name}" || true)"
        if [[ "${class}" == "copr" ]]; then
            if [[ "${origin}" != "${id}" && "${origin}" != "_${id}" ]]; then
                printf 'VIOLATION\t%s\tinstalled from a COPR that ZackOS does not use: %s\n' "${name}" "${origin}"
                bad=1
            elif [[ "${allow}" != *" ${name} "* ]]; then
                printf 'VIOLATION\t%s\tinstalled from %s but not in the allowlist\n' "${name}" "${origin}"
                bad=1
            fi
        fi
        if [[ "${source}" == "fedora" && ( "${class}" == "copr" || "${class}" == "other" ) ]]; then
            printf 'VIOLATION\t%s\tmanifest requires fedora but it is installed from %s\n' "${name}" "${origin}"
            bad=1
        fi
    done
    return "${bad}"
}

# repo_closure_gaps <owner/project> <name>...: stdin lines "package<TAB>requires<TAB>origin of the
# requirement". Prints each COPR-provided dependency of an allowlisted package that is not itself
# in the allowlist. Returns 1 if there are gaps.
repo_closure_gaps() {
    local spec="${1:?owner/project required}" id pkg req origin bad=0 allow=" "
    shift
    id="$(repo_copr_id "${spec}")" || return 2
    for pkg in "$@"; do allow+="${pkg} "; done
    while IFS=$'\t' read -r pkg req origin; do
        [[ "${allow}" == *" ${pkg} "* ]] || continue
        [[ "${origin}" == "${id}" ]] || continue
        if [[ "${allow}" != *" ${req} "* ]]; then
            printf 'GAP\t%s\trequires %s which comes from the COPR but is not in the allowlist\n' "${pkg}" "${req}"
            bad=1
        fi
    done
    return "${bad}"
}

# repo_enable_steps <owner/project> [chroot]: print the steps, one per line, as
#   description<TAB>command<TAB>undo
# Order matters: the isolation override is written BEFORE the repository is enabled, so there is
# never a moment where the repository is active without its allowlist.
# The override content is passed as the file given in OVERRIDE_SRC (a path the caller created).
repo_enable_steps() {
    local spec="${1:?owner/project required}" chroot="${2:-${REPO_DEFAULT_CHROOT}}" file src
    repo_valid_spec "${spec}" || return 2
    file="${REPO_OVERRIDE_DIR}/$(repo_override_filename "${spec}")"
    src="${OVERRIDE_SRC:-/path/to/generated-override.repo}"
    printf 'Write the isolation override\tsudo install -m 0644 %s %s\tsudo rm -- %s\n' "${src}" "${file}" "${file}"
    printf 'Enable the COPR\tsudo dnf5 copr enable %s %s\tsudo dnf5 copr disable %s\n' "${spec}" "${chroot}" "${spec}"
}

# repo_disable_steps <owner/project>
repo_disable_steps() {
    local spec="${1:?owner/project required}" chroot="${2:-${REPO_DEFAULT_CHROOT}}"
    repo_valid_spec "${spec}" || return 2
    printf 'Disable the COPR\tsudo dnf5 copr disable %s\tsudo dnf5 copr enable %s %s\n' "${spec}" "${spec}" "${chroot}"
}

# --- LOCKED execution -------------------------------------------------------------------------
_repo_locked() {
    log_error "COPR operations are locked (ADR 0005). They need the owner's explicit approval in a later phase."
    log_info "Use 'zackos repo show-override' or the *_steps functions to review the plan."
    return "${ZACKOS_EXIT_LOCKED}"
}

repo_enable_execute() { [[ "${ZACKOS_COPR_OPS_LOCKED}" == "1" ]] && _repo_locked; }
repo_disable_execute() { [[ "${ZACKOS_COPR_OPS_LOCKED}" == "1" ]] && _repo_locked; }
